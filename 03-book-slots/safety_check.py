"""Compare our safety tags with the 60 messages Hannah Lindqvist checked by hand.

Reads the fault batch, the stage 02 tags and the stage 03 schedule, checks
they cover the same 300 messages, and writes results/safety_report.md with
message IDs only. Runs offline, no model calls.

Usage:
    python safety_check.py
"""

from __future__ import annotations

import csv
import json
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "01-urgency-rules"))

from triage import load  # noqa: E402

SAFETY_CODES = ("BRK", "ABS", "ESP", "EPAS")
CALM = re.compile(r"no rush|not urgent|happy to wait|when convenient|whenever|sorry to bother|"
                  r"quick question|no hurry|at my next visit|hope your week|not dramatic", re.I)
SEVERE = re.compile(r"\bfloor\b|\bfluid\b|went long|goes long|sinks?|spongy|grabs|"
                    r"\block\w*\b|slid\b|jerks?\b|heavy|stiff|unsettled|cut power", re.I)


def read(path: Path) -> dict[str, dict]:
    with path.open(encoding="utf-8") as f:
        return {r["message_id"]: r for r in csv.DictReader(f)}


def pct(a: int, b: int) -> str:
    return f"{a}/{b}" + (f" ({100 * a // b}%)" if b else "")


def main(argv: list[str]) -> int:
    faults = Path(argv[1]) if len(argv) > 1 else ROOT / "01-urgency-rules/data/overnight_fault_messages_2026-11-16.csv"
    messages, errors = load(faults)
    msgs = {m.message_id: m for m in messages}
    tags = read(ROOT / "02-classify-messages/results/tags.csv")
    sched = read(HERE / "results/schedule.csv")
    summary = json.loads((HERE / "results/summary.json").read_text(encoding="utf-8"))

    if errors or not (set(msgs) == set(tags) == set(sched)) or len(msgs) != 300:
        raise SystemExit("fault batch, tags and schedule do not cover the same 300 messages")

    hand = [m for m in messages if m.hand_checked and m.hand_checked_safety_fault]
    caught = [m for m in hand if tags[m.message_id]["tag"] == "safety_urgent"]
    misses = [m for m in hand if tags[m.message_id]["tag"] != "safety_urgent"]
    by_model = sum(tags[m.message_id]["model_tag"] == "safety_urgent" for m in hand)

    def has_code(m):
        return m.vehicle_alert_code.split("_")[0] in SAFETY_CODES

    def calm(m):
        return bool(CALM.search(f"{m.message_subject}. {m.message_text}"))

    groups = {
        "Alert code NONE": [m for m in hand if m.vehicle_alert_code.upper() == "NONE"],
        "Safety alert code (BRK, ABS, ESP, EPAS)": [m for m in hand if has_code(m)],
        "Calm or polite tone": [m for m in hand if calm(m)],
        "Calm tone and code NONE": [m for m in hand if calm(m) and m.vehicle_alert_code.upper() == "NONE"],
    }
    group_rows = "\n".join(
        f"| {name} | {len(ms)} | {sum(tags[m.message_id]['tag'] == 'safety_urgent' for m in ms)} |"
        for name, ms in groups.items())

    miss_rows = "\n".join(
        f"| {m.message_id} | {tags[m.message_id]['tag']} | {m.vehicle_alert_code} | "
        f"{tags[m.message_id]['source']} |" for m in misses) or "| none | | | |"

    safety_sched = [s for s in sched.values() if s["tag"] == "safety_urgent"]
    safety_sched.sort(key=lambda s: int(s["rank"]))
    out_of_order = [b["message_id"] for a, b in zip(safety_sched, safety_sched[1:])
                    if (b["slot_date"], b["slot_start_time"]) < (a["slot_date"], a["slot_start_time"])]
    hand_sched = [sched[m.message_id] for m in hand]
    not_in_bay = [s["message_id"] for s in hand_sched if s["slot_type"] != "service_center_bay"]
    tiers = Counter(s["tier"] for s in hand_sched)
    days = Counter(s["slot_date"] for s in hand_sched)

    unchecked = [m for m in messages if tags[m.message_id]["tag"] == "safety_urgent"
                 and not m.hand_checked]

    def severity(m):
        text = f"{m.message_subject}. {m.message_text}"
        return (not has_code(m), not SEVERE.search(text), m.received_at)
    unchecked.sort(key=severity)
    unchecked_rows = "\n".join(
        f"| {m.message_id} | {m.vehicle_alert_code} | "
        f"{'yes' if SEVERE.search(m.message_subject + '. ' + m.message_text) else ''} | "
        f"{sched[m.message_id]['slot_date']} {sched[m.message_id]['slot_start_time']} |"
        for m in unchecked)

    day_rows = "\n".join(
        f"| {d} | {c.get('safety_urgent', 0)} | {c.get('soon', 0)} | {c.get('routine', 0)} |"
        for d, c in summary["bookings_by_day"].items())
    checks = "\n".join(f"- {'PASS' if ok else 'FAIL'}: {name}" for name, ok in summary["checks"].items())

    report = f"""# Safety report: week of 16 to 21 November 2026

Generated by `safety_check.py` from the fault batch, `02-classify-messages/results/tags.csv` and `results/schedule.csv`. Message IDs only, no message text or names.

## Recall against Hannah Lindqvist's 60 hand-checked messages

**{pct(len(caught), len(hand))} hand-checked safety faults are tagged safety urgent.**

What this can and can't show: all {len(hand)} hand-checked rows are confirmed safety faults, and none is confirmed safe. So this is **recall only**. Precision (how many of our {summary['safety_urgent']} safety tags are real) can't be measured from this set.

- Caught by the model by itself: **{pct(by_model, len(hand))}**
- Caught after the stage 01 rules backstop: **{pct(len(caught), len(hand))}**

## Misses

| Message | Our tag | Alert code | Decided by |
| --- | --- | --- | --- |
{miss_rows}

## The cases most likely to slip

| Group | Hand-checked | Tagged safety urgent |
| --- | --- | --- |
{group_rows}

{len(groups['Alert code NONE'])} of the {len(hand)} confirmed safety faults had no dashboard alert at all, and {len(groups['Calm or polite tone'])} were written in a calm or polite tone. A rule that only read alert codes, or a model that read tone, would miss these.

## Where the 60 landed in the schedule

- Monday tier (same-day bay): **{tiers.get('safety_tier_1_same_day', 0)}**. Tier 2 (earliest bay after Monday): **{tiers.get('safety_tier_2_next_bay', 0)}**.
- By day: {', '.join(f'{d}: {n}' for d, n in sorted(days.items()))}.
- Hand-checked safety faults not in a service center bay: **{', '.join(not_in_bay) or 'none'}**.
- Safety messages booked after a lower-ranked safety message: **{', '.join(out_of_order) or 'none'}**.

The Monday tier is ordered by cars already off the road, then the most severe symptoms, then hand-checked faults. So most of the 60 are in tier 2. All 60 are booked by {max(days)}.

## Schedule checks

{checks}

## Bookings by day

| Day | Safety urgent | Soon | Routine |
| --- | --- | --- | --- |
{day_rows}

Monday has {summary['safety_booked_monday']} service center bays for {summary['safety_urgent']} safety urgent messages. Every safety driver gets a call on Monday, is told not to drive, and gets a tow timed to their slot. The last safety booking is {summary['last_safety_booking']}.

## Next batch for Hannah: {len(unchecked)} safety urgent messages she didn't check

Ordered by how severe they look: a safety alert code first, then severe wording, then oldest.

| Message | Alert code | Severe wording | Booked |
| --- | --- | --- | --- |
{unchecked_rows}
"""
    (HERE / "results/safety_report.md").write_text(report, encoding="utf-8")
    print(f"recall {len(caught)}/{len(hand)}, misses {len(misses)}, "
          f"model alone {by_model}, unchecked safety {len(unchecked)}")
    for name, ms in groups.items():
        print(f"  {name}: {sum(tags[m.message_id]['tag'] == 'safety_urgent' for m in ms)}/{len(ms)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
